-- 챗봇 대화 (7단계 C1). 대화방(chat_sessions) 하나에 턴(chat_turns = 사용자 질문 + 그 질문의 LLM 요청)이 쌓인다.
-- 챗봇 답변은 여기 복사하지 않는다 — 답·상태(PENDING/COMPLETED/FAILED)·실패 사유·토큰의 원본은 llm_requests 한 곳.
-- (답을 따로 저장하면 "결과 도착 → 두 테이블 갱신"이 필요해지고, 타임아웃·늦은 결과·중복 결과마다 둘이 어긋날 수 있다)
ALTER TABLE llm_requests DROP CONSTRAINT ck_llm_requests_type;
ALTER TABLE llm_requests ADD CONSTRAINT ck_llm_requests_type CHECK (type IN ('EVENT_COPY', 'EVENT_SEARCH', 'CHAT'));

CREATE TABLE chat_sessions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 대화는 회원의 것이라 FK + CASCADE (llm_requests 처럼 감사 기록이 아니다 — 회원이 지워지면 대화도 지운다)
    user_id         BIGINT                      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_message_at TIMESTAMP(6) WITH TIME ZONE NOT NULL     -- 목록 정렬 (최근 대화가 위)
);

CREATE INDEX idx_chat_sessions_user_last ON chat_sessions (user_id, last_message_at DESC);

CREATE TABLE chat_turns
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     BIGINT                      NOT NULL REFERENCES chat_sessions (id) ON DELETE CASCADE,
    question       VARCHAR(500)                NOT NULL,    -- = ChatInput.MESSAGE_MAX
    -- 턴 하나 = LLM 요청 하나. UNIQUE 라 한 요청이 두 턴에 붙지 않는다
    llm_request_id UUID                        NOT NULL UNIQUE REFERENCES llm_requests (request_id),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_chat_turns_question CHECK (btrim(question) <> '')
);

-- 대화방의 턴을 순서대로 (id 가 곧 순서 — IDENTITY 는 증가만 한다)
CREATE INDEX idx_chat_turns_session ON chat_turns (session_id, id);
