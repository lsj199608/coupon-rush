-- 선착순 쿠폰 (이벤트 단위)
CREATE TABLE coupons
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)                NOT NULL,
    total_quantity  INTEGER                     NOT NULL,
    issued_quantity INTEGER                     NOT NULL DEFAULT 0,
    issue_start_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    issue_end_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_coupons_total_quantity CHECK (total_quantity > 0),
    -- 최후의 안전망. 다만 lost update(두 요청이 같은 값을 읽고 같은 값으로 덮어씀)는 이 제약으로 막을 수 없다
    CONSTRAINT ck_coupons_issued_quantity CHECK (issued_quantity BETWEEN 0 AND total_quantity),
    CONSTRAINT ck_coupons_issue_period CHECK (issue_start_at < issue_end_at)
);

-- 발급 이력. 한 사람은 같은 쿠폰을 한 번만 받는다 (동시 중복 요청도 DB 가 최종적으로 막는다)
CREATE TABLE coupon_issues
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT                      NOT NULL REFERENCES coupons (id),
    user_id   BIGINT                      NOT NULL REFERENCES users (id),
    issued_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_coupon_issues_coupon_user UNIQUE (coupon_id, user_id)
);

-- "내 쿠폰 목록" 조회용 (coupon_id 쪽은 유니크 인덱스의 선두 컬럼이라 따로 필요 없음)
CREATE INDEX idx_coupon_issues_user_id ON coupon_issues (user_id);
