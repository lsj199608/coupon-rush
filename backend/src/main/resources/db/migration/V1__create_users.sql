-- 회원 테이블. "user" 는 PostgreSQL 예약어라 users.
-- 식별 키는 (provider, provider_id). 이메일은 제공자/동의 여부에 따라 없을 수 있다.
CREATE TABLE users
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider    VARCHAR(20)              NOT NULL,
    provider_id VARCHAR(100)             NOT NULL,
    nickname    VARCHAR(50)              NOT NULL,
    email       VARCHAR(255),
    role        VARCHAR(20)              NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_users_provider_provider_id UNIQUE (provider, provider_id),
    -- enum(OAuth2Provider, Role) 에 값을 추가하면 새 마이그레이션으로 이 제약도 바꿔야 한다
    -- (FlywayMigrationTest 가 enum 과 제약 불일치를 잡아준다)
    CONSTRAINT users_provider_check CHECK (provider IN ('KAKAO', 'NAVER', 'GOOGLE')),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);
